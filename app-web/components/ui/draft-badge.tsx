/**
 * Notebook-style "pencilled in" label for AI-generated content that no expert
 * has verified yet. Render it only when `isDraftContent(...)` is true.
 */
export function DraftBadge({ className = "" }: { className?: string }) {
  return (
    <span className={`draft-badge ${className}`.trim()} role="note" title="Generated by AI and not yet checked by a subject expert">
      Draft: AI-generated, not yet expert-verified
    </span>
  );
}
